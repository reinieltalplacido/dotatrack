export function getHeroLoreById(id: number): HeroLoreEntry | undefined {
  return HERO_LORE_DATABASE.find((h) => h.id === id);
}

export function searchHeroesByLore(query: string): HeroLoreEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return HERO_LORE_DATABASE;
  return HERO_LORE_DATABASE.filter(
    (h) =>
      h.name.toLowerCase().includes(q) ||
      h.realName.toLowerCase().includes(q) ||
      h.shortName.toLowerCase().includes(q)
  );
}
